Page({
  data: {
    statusBarHeight: 20,
    navBarHeight: 44,
    title: '用户服务协议',
    updated: '',
    sections: []
  },
  onLoad(query) {
    const type = DOCS[query.type] ? query.type : 'terms'
    const doc = DOCS[type]
    this.setData({
      statusBarHeight: app.globalData.statusBarHeight,
      navBarHeight: app.globalData.navBarHeight,
      type: type,
      title: doc.title,
      updated: doc.updated,
      sections: doc.sections
    })
    wx.setNavigationBarTitle({ title: doc.title })
  },
  back() {
    wx.navigateBack({ fail: function () { wx.switchTab({ url: '/pages/home/index' }) } })
  },
  switchDoc(e) {
    const type = e.currentTarget.dataset.type
    const doc = DOCS[type]
    if (!doc) return
    this.setData({ type: type, title: doc.title, updated: doc.updated, sections: doc.sections })
    wx.pageScrollTo({ scrollTop: 0, duration: 0 })
  }
})
